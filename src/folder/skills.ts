// The agent skills the Folder carries (decision F14, addendum of 2026-10-14):
// procedures a harness offers by their description and loads when the work
// matches, rendered by the same transaction as AGENTS.md and the manual, in
// the Folder's locale, and never edited in place. Each is written once and
// lands byte-identical in `.agents/skills/<name>/SKILL.md` (Codex) and
// `.claude/skills/<name>/SKILL.md` (Claude Code). Every paragraph is written
// in both languages side by side, so the two can only change together;
// commands, codes and paths stay in English. Text addressed to the agent is in
// tykání; what the agent says to the person is quoted in vykání (root decision
// 0199).

type Locale = FolderProfile["locale"];
const t = (cs: string, en: string): Text => ({ cs, en });
const blank = t("", "");

const generated = t(
  "generováno Lazuriem, needituj: upravený soubor zablokuje každé nové vykreslení Folderu, dokud se nevrátí do původní podoby",
  "generated by Lazurio, do not edit: an edited file blocks every re-render of the Folder until it is restored",
);

// One SKILL.md: the frontmatter both harnesses and Hermes read (the
// description as a JSON string, which is a valid YAML double-quoted scalar
// whatever it holds), then the title, the revision note and the body. Buddy's
// skills (buddy.ts) are written the same way, with their own note.
export function skillDocument(
  locale: Locale,
  name: string,
  description: Text,
  title: Text,
  body: readonly Text[],
  note: Text = generated,
): string {
  return [
    "---",
    `name: ${name}`,
    `description: ${JSON.stringify(description[locale])}`,
    "---",
    "",
    `# ${title[locale]}`,
    `<!-- ${instructionTemplateRevision}; ${note[locale]} -->`,
    "",
    ...body.map((text) => text[locale]),
    "",
  ].join("\n");
}

