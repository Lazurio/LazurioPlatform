function skillText(source: InstructionSource, name: SkillName): string {
  const { locale } = source.profile;
  switch (name) {
    case "new-module":
      return skillDocument(
        locale,
        name,
        newModuleDescription,
        { cs: "Nový modul", en: "A new module" },
        newModule(source.preset),
      );
    case "henry-review":
      return skillDocument(
        locale,
        name,
        henryReviewDescription,
        { cs: "Review personou", en: "Review by the persona" },
        henryReview,
      );
    case "module-standard":
      return skillDocument(
        locale,
        name,
        moduleStandardDescription,
        {
          cs: "Modul podle Lazurio Module Standard",
          en: "A module to the Lazurio Module Standard",
        },
        moduleStandard,
      );
  }
}

// Every skill file of this Folder, keyed by its path: the same bytes under
// each harness's skill directory.
export function renderSkills(
  input: unknown,
): Readonly<Record<SkillPath, string>> {
  const source = parseInstructionSource(input);
  const files: Partial<Record<SkillPath, string>> = {};
  for (const name of skillNames) {
    const text = skillText(source, name);
    for (const root of skillRoots) files[`${root}/${name}/SKILL.md`] = text;
  }
  return Object.freeze(files) as Readonly<Record<SkillPath, string>>;
}
