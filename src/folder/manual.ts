// The agent manual shipped with the product (decision F14): complete for an
// agent that starts work on this Machine, in the Folder's locale (`cs` or
// `en`, the same file names), rendered into `manual/` by the same transaction
// as AGENTS.md and never edited in place. Every paragraph is written in both
// languages side by side, so the two can only change together; technical
// identifiers (commands, codes, paths, preset names) stay in English.
// `this-machine.md` is a projection of the preset and the recorded Machine
// binding, `troubleshooting.md` of the preset; the rest is the same on every
// Machine of one locale.

type Locale = FolderProfile["locale"];
const t = (cs: string, en: string): Text => ({ cs, en });
const same = (text: string): Text => ({ cs: text, en: text });
const blank = same("");

function document(
  locale: Locale,
  title: Text,
  note: string,
  body: readonly Text[],
): string {
  return [
    `# ${title[locale]}`,
    `<!-- ${instructionTemplateRevision}; ${note} -->`,
    ...body.map((text) => text[locale]),
    "",
  ].join("\n");
}

