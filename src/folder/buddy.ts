const skills: Readonly<Record<BuddySkillName, BuddySkill>> = {
  "lazurio-t3-orchestration": threads,
  "lazurio-mausbot": mausbot,
  "lazurio-buddy-pomocnici": helpers,
};

export function buddySkillDocument(
  locale: Locale,
  name: BuddySkillName,
): string {
  const skill = skills[name];
  return skillDocument(
    locale,
    name,
    skill.description,
    skill.title,
    skill.body,
    layerNote,
  );
}

// Every file of the layer from one validated composition, in the Folder's
// locale.
export function renderBuddyLayer(
  input: unknown,
): Readonly<Record<BuddyLayerPath, string>> {
  const source = parseInstructionSource(input);
  const files: Partial<Record<BuddyLayerPath, string>> = {
    [buddyRulesPath]: renderBuddyRules(source),
  };
  for (const name of buddySkillNames)
    files[buddySkillPath(name)] = buddySkillDocument(
      source.profile.locale,
      name,
    );
  return Object.freeze(files) as Readonly<Record<BuddyLayerPath, string>>;
}
