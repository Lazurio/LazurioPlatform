export function renderBuddyRules(input: unknown): string {
  const source = parseInstructionSource(input);
  const locale = source.profile.locale;
  const pick = (text: Text) => text[locale];
  return [
    "# Buddy",
    `<!-- ${instructionTemplateRevision}; ${layerNote[locale]} -->`,
    "",
    ...intro.map(pick),
    "",
    ...role.map(pick),
    "",
    ...mandates.map(pick),
    "",
    ...profile.map(pick),
    "",
    ...places.map(pick),
    "",
    ...bubble.map(pick),
    "",
    ...layers.map(pick),
    "",
    // The default voice only: Hermes blocks a whole context file in which its
    // injection scan finds anything, and a custom voice is text this product
    // does not control (agent/prompt_builder.py `_scan_context_content`; only
    // the user's SOUL.md is merely warned about). Buddy's own tone is his
    // persona's.
    ...voiceSection(locale),
    pick(userAddress),
    "",
    pick(t("## Jak se tu pracuje", "## How work is done here")),
    pick(environmentWording),
    pick(questionTool),
    pick(draftRule),
    pick(fullAccess),
    ...personalspaceRules.map(pick),
    "",
  ].join("\n");
}

