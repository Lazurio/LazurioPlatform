// The persona's names, or the generic words when there is none.
type Names = Readonly<{
  buddy: Text;
  user: Text;
  userDative: Text;
  informal: boolean;
  named: boolean;
}>;

function namesOf(persona: Persona | undefined): Names {
  if (persona === undefined)
    return {
      buddy: t("Buddy", "Buddy"),
      user: t("uživatel", "the user"),
      userDative: t("uživateli", "the user"),
      informal: false,
      named: false,
    };
  return {
    buddy: t(persona.buddyName, persona.buddyName),
    user: t(persona.user.nominative, persona.user.nominative),
    userDative: t(persona.user.dative, persona.user.nominative),
    informal: persona.address === "ty",
    named: true,
  };
}

