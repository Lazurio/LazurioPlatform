// Buddy GEN4 (root decision 0210, addenda of 2026-11-16 and 2026-11-17; plan
// LZD-0033, slice R2): Buddy is one long T3 Code thread in its own project,
// a `Buddy` folder beside the Lazurio Folder, in the same T3 Code server as
// Chat (Lazurio/t3code#214, `T3CODE_LAZURIO_BUDDY_FOLDER`). Its instructions
// are this folder's `AGENTS.md` and its skills, which Lazurio writes for a
// person whose Machines handover carries `entry.buddy.generation: 4`
// (HumanAndMachine-ai/Machines#1330) and overwrites on every refresh.
//
// What the harnesses read there (plan LZD-0033, V1 and the first pilot
// thread): Codex and Claude Code both load `AGENTS.md` when no `CLAUDE.md`
// lies beside it, so there is none; Codex finds skills in `.agents/skills/`,
// Claude Code in `.claude/skills/`, so each skill is written to both, byte
// for byte, as in the Folder. The Folder's own `AGENTS.md` does not reach
// this folder, so the rules Buddy needs from it are composed here from the
// same fragments; the user's personal instructions do reach it.
//
// One mechanism in two profiles (Matěj 2026-11-17): `buddy`, the personal
// representative of one person (0089), and `employee`, the agent of an
// Organization's persona acting for itself within the mandates people
// recorded (0220). The persona (Buddy's name, the user's name and the
// address) comes from Settings → Buddy (`persona.json`); without it the text
// speaks of "the user" and keeps the formal address. No person's data is
// written into this source: names are filled in on the person's own
// Environment from that file.

