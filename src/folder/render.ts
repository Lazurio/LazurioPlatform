/** The Environment a tool is offered in (`toolOffered`): the preset and
 * whether it runs on Linux. */
export type ToolEnvironment = Readonly<{ preset: PresetName; linux: boolean }>;

export const toolEnvironmentOf = (
  preset: PresetName,
  profile: Pick<FolderProfile, "os">,
): ToolEnvironment => ({ preset, linux: profile.os === "linux" });

/** The tools agents are to use: the required ones and the enabled ones that
 * this Environment offers, in catalog order. A stored selection naming a
 * tool the Environment does not offer (gogcli on a work Environment) is
 * readable and is not rendered (decision F44). */
export const renderedTools = (
  tools: readonly string[],
  environment: ToolEnvironment,
) => activeTools(tools).filter((entry) => toolOffered(entry, environment));

// One line per tool agents are to use (`renderedTools`). `text` selects
// what the line says about the tool: its purpose, with the marker of an
// operator's note (AGENTS.md), or its purpose and usage followed by the
// quoted note (the manual).
export function toolLines(
  tools: readonly string[],
  environment: ToolEnvironment,
  locale: FolderProfile["locale"],
  text: "purpose" | "usage",
  notes: ToolNotes = {},
): string[] {
  return renderedTools(tools, environment).flatMap(({ name, activation }) => {
    const note = Object.hasOwn(notes, name) ? notes[name] : undefined;
    const line = `- \`${name}\` (${tierLabels[activation.tier][locale]}): ${
      text === "purpose"
        ? `${activation.purpose[locale]}${note === undefined ? "" : ` ${noteMarker[locale]}`}`
        : `${activation.purpose[locale]} ${activation.usage[locale]}`
    }`;
    if (text === "purpose" || note === undefined) return [line];
    // Inside the list item: the attribution, then every line of the note as
    // a quoted line (`quoteToolNote` keeps it one literal block).
    return [
      line,
      `  ${noteAttribution[locale]}`,
      ...quoteToolNote(note).map((quoted) => `  ${quoted}`),
    ];
  });
}

