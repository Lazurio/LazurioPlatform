// Version the template set (AGENTS.md and the manual) independently from
// future persisted preference schemas. Every change of the generated bytes
// moves it to the next number; tests/folder-template-revision.test.ts pins the
// rendered digest of the current one (decision F14, addendum 2026-10-03).
export const instructionTemplateRevision = "base-instructions-97";

// Template revisions are ordered by their number. A Folder rendered by an
// older revision is re-rendered by the next change of the generated Folder
// (a refresh or a profile change) when every file still has its recorded
// digest (decision F14). A revision this product does not know, a newer one
// or one of another form, is never re-rendered or downgraded by it.
function templateRevisionNumber(revision: string): number | null {
  const match = /^base-instructions-([1-9][0-9]{0,8})$/.exec(revision);
  return match === null ? null : Number(match[1]);
}

/** A template revision of this product's form, whatever its number. */
export const isTemplateRevision = (revision: string) =>
  templateRevisionNumber(revision) !== null;

export function isOlderTemplateRevision(
  revision: string,
  than: string = instructionTemplateRevision,
): boolean {
  const recorded = templateRevisionNumber(revision);
  const current = templateRevisionNumber(than);
  return recorded !== null && current !== null && recorded < current;
}

// What the renderer needs and nothing else: the preset, the immutable Machine
// binding (null on a workstation), the profile, the enabled catalog tools
// (decision F18), the operator's notes on them (F18 addendum 2026-09-27) and
// the Organization settings the Folder applies (root decision 0194, F45).
// Validated as one composition. A source without `tools` has nothing enabled,
// one without `toolNotes` no note and one without `organizationSettings`
// nothing governed; the parsed source always names all three. `tools` and
// `toolNotes` are the person's own selection; what agents are told to use is
// that selection without what the Organization does not allow
// (`agentTools`). `chatgptAppsAllowed` is the person's choice of their
// ChatGPT account's apps where no Organization governs (decision F42's
// addendum of 2026-10-27): `true`, or absent for off.
export type InstructionSource = Readonly<{
  agentVoice?: AgentVoice;
  preset: PresetName;
  machine: MachineBinding | null;
  profile: FolderProfile;
  tools: readonly string[];
  toolNotes: ToolNotes;
  organizationSettings: OrganizationSettingsValues;
  chatgptAppsAllowed?: true;
}>;

export function parseInstructionSource(input: unknown): InstructionSource {
  const withVoice = ownDataValue(input, "agentVoice") !== undefined;
  const withTools = ownDataValue(input, "tools") !== undefined;
  const withNotes = ownDataValue(input, "toolNotes") !== undefined;
  const withSettings =
    ownDataValue(input, "organizationSettings") !== undefined;
  const withChatgpt = ownDataValue(input, "chatgptAppsAllowed") !== undefined;
  const value = stateFields(input, [
    ...(withVoice ? ["agentVoice"] : []),
    "preset",
    "machine",
    "profile",
    ...(withTools ? ["tools"] : []),
    ...(withNotes ? ["toolNotes"] : []),
    ...(withSettings ? ["organizationSettings"] : []),
    ...(withChatgpt ? ["chatgptAppsAllowed"] : []),
  ]);
  const preset = parsePresetName(value.preset);
  const machine = parseMachineBinding(value.machine);
  const profile = parseFolderProfile(value.profile);
  validatePresetComposition(preset, machine, profile);
  const tools = withTools ? parseEnabledTools(value.tools) : Object.freeze([]);
  const notes = withNotes
    ? parseToolNotes(value.toolNotes, tools)
    : Object.freeze({});
  const settings = withSettings
    ? parseOrganizationSettingsValues(value.organizationSettings)
    : Object.freeze({});
  // A personal Environment and the person's own computer decide alone.
  if (Object.keys(settings).length > 0 && !organizationGoverns(preset))
    throw new Error("No Organization governs this Environment");
  if (
    withChatgpt &&
    (value.chatgptAppsAllowed !== true || organizationGoverns(preset))
  )
    throw new Error("Invalid ChatGPT apps preference");
  return Object.freeze({
    preset,
    machine,
    profile,
    tools,
    toolNotes: notes,
    organizationSettings: settings,
    ...(withVoice ? { agentVoice: parseAgentVoice(value.agentVoice) } : {}),
    ...(withChatgpt ? { chatgptAppsAllowed: true as const } : {}),
  });
}

/** Whether agents may use the ChatGPT account's apps on the Environment of
 * this source, and who decided (decision F42's addendum of 2026-10-27). */
export function sourceChatgptApps(
  source: Pick<
    InstructionSource,
    "preset" | "organizationSettings" | "chatgptAppsAllowed"
  >,
): ChatgptAppsPolicy {
  return chatgptAppsPolicyOf(
    source.preset,
    source.organizationSettings,
    source.chatgptAppsAllowed === true,
  );
}

export function instructionSource(
  preferences: FolderPreferences,
): InstructionSource {
  return Object.freeze({
    ...(preferences.agentVoice === undefined
      ? {}
      : { agentVoice: preferences.agentVoice }),
    preset: preferences.preset.name,
    machine: preferences.machine,
    profile: preferences.profile,
    tools: enabledTools(preferences),
    toolNotes: toolNotes(preferences),
    organizationSettings: folderOrganizationSettings(preferences),
    ...(personalChatgptApps(preferences)
      ? { chatgptAppsAllowed: true as const }
      : {}),
  });
}

/** What agents are told to use (decision F18, F45): the person's selection
 * and notes without the tools the Organization does not allow here, and
 * those tools, for the line that says why they are missing. */
export function agentTools(
  source: Pick<
    InstructionSource,
    "tools" | "toolNotes" | "organizationSettings"
  >,
): Readonly<{
  tools: readonly string[];
  notes: ToolNotes;
  forbidden: readonly string[];
}> {
  const settings = source.organizationSettings;
  return Object.freeze({
    tools: effectiveTools(source.tools, settings),
    notes: effectiveNotes(source.toolNotes, settings),
    forbidden: forbiddenTools(settings),
  });
}

