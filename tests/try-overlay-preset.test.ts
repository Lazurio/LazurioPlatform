/** A Folder for `handover`, recorded with `preset` the way it can come to
 * be. A preset the handover offers is what `folder-init` records. One it
 * does not offer (Work under try-01's Team assignment) has a history:
 * adopted from an earlier handover without the assignment, which left the
 * choice to the operator (`--preset`, recorded as explicit), then refreshed
 * when the handover stated the assignment, which keeps it. `revision` is the
 * Folder's then. */
async function folderFor(
  preset: PresetName,
  handover: Readonly<{ owner: Readonly<Record<string, unknown>> }>,
) {
  const parent = await realpath(await mkdtemp(join(tmpdir(), "try-overlay-")));
  const folder = join(parent, "Lazurio");
  await mkdir(folder, { mode: 0o700 });
  await mkdir(join(folder, "organizations"), { mode: 0o755 });
  await mkdir(join(folder, "personalspace"), { mode: 0o700 });
  const machine = binding(handover);
  const profile = presetProfile(preset, executionOs(process.platform), {
    locale: "cs",
  });
  if (selectablePresets(machine).includes(preset)) {
    await initializeHandoverFolder(folder, { preset, machine, profile });
    return { parent, folder, machine, profile, revision: 1 };
  }
  const { assignment: _, ...earlier } = handover.owner;
  await initializeHandoverFolder(folder, {
    preset,
    machine: binding({ ...handover, owner: earlier }),
    profile,
  });
  expect(await refreshFolder(folder, machine)).toEqual({
    kind: "refreshed",
    revision: 2,
  });
  return { parent, folder, machine, profile, revision: 2 };
}
