import { expect, test } from "bun:test";
import { createHash } from "node:crypto";
import type { MachineBinding } from "../src/folder/machine-binding";
import {
  allowedPresets,
  derivePreset,
  githubIdentity,
  type PresetName,
  presetProfile,
  selectablePresets,
} from "../src/folder/presets";
import { renderOutputs } from "../src/folder/preview";
import {
  environmentKind,
  shellDocument,
} from "../src/launchpad/shell-document";
import { controls, tryCases } from "./fixtures/try-environments";

// Plan DEV-6668 slice 4, decision F55's addendum of 2026-10-20: the Try
// overlay preset, the settings of a public Environment as one frozen record,
// selected only by the handover's `entry.audience: "public"`.

const emptyCatalog = { kind: "catalog", organizations: [] } as const;

/** Every generated file of a Folder, by its SHA-256: equal digests are equal
 * bytes. */
function generated(
  preset: PresetName,
  machine: MachineBinding,
  locale: "cs" | "en",
) {
  const outputs = renderOutputs({
    preset,
    machine,
    profile: presetProfile(preset, "linux", { locale }),
  });
  return Object.fromEntries(
    Object.entries(outputs).map(([path, content]) => [
      path,
      createHash("sha256").update(content).digest("hex"),
    ]),
  );
}

// --- Goldens, recorded before the overlay ------------------------------

// Recorded from the commit before the overlay (this file's first commit,
// with `src/` as `origin/main` had it), so a difference here is a change
// the overlay made to an Environment that is not public. Review the
// snapshot only when such a change is deliberate.
for (const control of controls)
  test(`golden: ${control.name} renders, derives, offers and is shown as before`, () => {
    expect({
      generated: {
        cs: generated(control.preset, control.machine, "cs"),
        en: generated(control.preset, control.machine, "en"),
      },
      derived: derivePreset(control.machine),
      allowed: allowedPresets(control.machine),
      selectable: selectablePresets(control.machine, control.preset),
      githubIdentity: githubIdentity(control.preset, control.machine),
      kind: environmentKind(control.preset, control.machine),
      shell: {
        cs: shellDocument({
          preset: control.preset,
          machine: control.machine,
          locale: "cs",
          catalog: emptyCatalog,
        }),
        en: shellDocument({
          preset: control.preset,
          machine: control.machine,
          locale: "en",
          catalog: emptyCatalog,
        }),
      },
    }).toMatchSnapshot();
  });

// The overlay changes no generated byte on try-01 either: what its agents
// read is slice 5's.
for (const entry of tryCases)
  test(`golden: ${entry.name} renders as before`, () => {
    expect({
      cs: generated(entry.preset, entry.machine, "cs"),
      en: generated(entry.preset, entry.machine, "en"),
    }).toMatchSnapshot();
  });
